import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(process.env.BUNDLED_NODE_MODULES+'/package.json');
const {chromium}=require('playwright');
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext();
const page=await context.newPage();
const errors=[];page.on('pageerror',error=>errors.push(error.message));
let release,held=false;
const gate=new Promise(resolve=>{release=resolve;});
await context.route('**/public/vectors.f32.gz',async route=>{held=true;await gate;await route.abort();});
const base=process.env.TNVED_TEST_URL||'http://127.0.0.1:8765/';
try{
  await page.goto(base);
  await page.locator('#load-status').filter({hasText:'Справочник загружен'}).waitFor({timeout:60000});
  const input=page.locator('#description'),results=page.locator('#results-content');
  await input.fill('Защитный щиток режущей головки бензокосы');
  await results.getByText(/Предварительный поиск по словам/).waitFor({timeout:10000});
  assert(await results.locator('.candidate').count()>0);
  assert.equal(await results.locator('.percent').count(),0);
  assert(await page.locator('#save-report').isDisabled());
  console.log('Automatic input search displays preliminary candidates.');
  await input.fill('Карбюратор');
  await results.getByText(/Точное совпадение названия/).waitFor({timeout:10000});
  assert(await page.locator('#search-button').isEnabled());
  console.log('Exact lookup stays available while model loading is stalled.');
  await input.fill('Защитный щиток режущей головки бензокосы');
  await input.press('Enter');
  await results.getByText(/Предварительный поиск по словам/).waitFor({timeout:10000});
  await results.getByText(/Смысловой поиск недоступен/).waitFor({timeout:60000});
  assert(held,'The vector download must have been intercepted');
  assert(await page.locator('#search-button').isEnabled());
  assert(await results.locator('.candidate').count()>0);
  console.log('Enter starts search; stalled model returns a visible fallback and unlocks the button.');
  await input.fill('Карбюратор');
  await page.locator('#search-button').click();
  await results.getByText(/Точное совпадение названия/).waitFor({timeout:10000});
  release();
  await page.waitForTimeout(1200);
  assert.match(await results.innerText(),/Точное совпадение названия/);
  assert.deepEqual(errors,[]);
  console.log('Button search and stale-result protection verified; no browser errors.');
}finally{release();await browser.close();}
